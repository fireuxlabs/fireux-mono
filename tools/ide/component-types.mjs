import { buildNuxt, loadNuxt, writeTypes } from '@nuxt/kit'
import {
  mkdir,
  mkdtemp,
  readFile,
  realpath,
  rm,
  writeFile,
} from 'node:fs/promises'
import { dirname, isAbsolute, join, relative, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseArgs } from 'node:util'

const root = fileURLToPath(new URL('../../', import.meta.url))
const outputName = 'fireux-ide-components.generated.d.ts'

async function generate(owner, workspaces) {
  const directory = await realpath(resolve(root, owner))
  const packagePath = relative(root, directory)
  if (!/^packages[/\\][^/\\]+[/\\][^/\\]+$/.test(packagePath)) {
    throw new Error(`Pass a FireUX package directory: ${owner}`)
  }

  const module = join(directory, 'src/module.ts')
  const runtime = join(directory, 'src/runtime')
  const output = join(directory, 'src', outputName)
  const temporaryRoot = join(root, '.nuxt')
  await mkdir(temporaryRoot, { recursive: true })
  const cwd = await mkdtemp(join(temporaryRoot, 'ide-components-'))
  let nuxt
  try {
    nuxt = await loadNuxt({
      cwd,
      dev: false,
      overrides: {
        _prepare: true,
        telemetry: false,
        extends: [runtime],
        modules: [module],
        runtimeConfig: { public: { fireux: { workspaces } } },
      },
    })
    await buildNuxt(nuxt)
    await writeTypes(nuxt)
    const declaration = join(nuxt.options.buildDir, 'types/components.d.ts')
    const contents = await readFile(declaration, 'utf8')
    const rebased = contents.replace(
      /import\(("(?:[^"\\]|\\.)*")\)/g,
      (match, specifier) => {
        const path = JSON.parse(specifier)
        if (!path.startsWith('.') && !isAbsolute(path)) return match
        const target = resolve(dirname(declaration), path)
        const local = relative(dirname(output), target).split(sep).join('/')
        return `import(${JSON.stringify(local.startsWith('.') ? local : `./${local}`)})`
      }
    )
    await writeFile(
      output,
      `// Generated by pnpm ide:component-types.\n${rebased}`
    )
    console.log(relative(root, output))
  } finally {
    await nuxt?.close()
    await rm(cwd, { recursive: true, force: true })
  }
}

const { positionals: owners, values } = parseArgs({
  allowPositionals: true,
  options: { workspace: { type: 'string', multiple: true } },
})
if (!owners.length) {
  console.error('Usage: pnpm ide:component-types <package-directory> [...]')
  process.exitCode = 1
} else {
  for (const owner of new Set(owners))
    await generate(owner, values.workspace ?? [])
}
